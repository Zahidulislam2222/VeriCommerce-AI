import { test, expect as baseExpect } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import AxeBuilder from '@axe-core/playwright';
import type { Page } from '@playwright/test';

test.setTimeout(180000);
test.use({ actionTimeout: 20000 });
const expect = baseExpect.configure({ timeout: 30000 });
async function settled(page: Page) { await expect(page.locator('#core-main')).toHaveAttribute('aria-busy', 'false', { timeout: 60000 }); await expect(page.locator('.core-alert')).toHaveCount(0); }
async function navigate(page: Page, label: string) { await page.locator('nav:visible').getByRole('button', { name: label, exact: true }).click(); await settled(page); }

test('real account, first CSV import, context, source graph, image review and isolation', async ({ page }, testInfo) => {
  const suffix = randomUUID().slice(0, 8);
  const productId = `browser-product-${suffix}`;
  const sourceId = `browser-source-${suffix}`;
  const email = `browser-${suffix}@example.test`;
  await page.goto('/engine#account');
  await settled(page);
  await expect(page.getByRole('button', { name: 'Create account', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  await page.getByLabel('Email address', { exact: true }).fill(email);
  await page.getByLabel('Password', { exact: true }).fill(`test-password-${suffix}`);
  await page.getByLabel('Workspace name', { exact: true }).fill(`Browser verification ${suffix}`);
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  await settled(page);
  await expect(page.getByRole('heading', { name: email, exact: true })).toBeVisible();
  const me = await (await page.request.get('/api/auth/me')).json();
  expect(me.authenticated).toBe(true);
  expect(me.capabilities).toContain('edit');
  const capabilities = await (await page.request.get('/api/capabilities')).json();
  const row: Record<string, string> = { product_id: productId, name: `Browser Headphone ${suffix}`, sku: `UI-${suffix}`, category: 'Audio', source_id: sourceId, source_name: `Browser catalog ${suffix}`, version: '1', date: '2026-10-18', label: 'battery', value: '40 hours', passage: 'Battery life is 40 hours with active noise cancellation disabled.', page: '1' };
  const columns: string[] = capabilities.uploads.csv_columns;
  const csv = `${columns.join(',')}\n${columns.map((column) => row[column] || '').join(',')}\n`;
  await navigate(page, 'Import catalog');
  await page.getByLabel('Catalog or source file').setInputFiles({ name: 'browser-catalog.csv', mimeType: 'text/csv', buffer: Buffer.from(csv) });
  await page.getByLabel('Stable source ID').fill(`upload-${suffix}`);
  await page.getByLabel('Source revision', { exact: true }).fill('1');
  await page.getByRole('button', { name: 'Upload and process', exact: true }).click();
  await settled(page);
  await expect(page.getByRole('status').filter({ hasText: 'succeeded' })).toBeVisible();
  await navigate(page, 'Retrieval inspector');
  await page.getByRole('textbox', { name: 'Question or constraints', exact: true }).fill('What is the battery life?');
  await page.getByLabel('First product').selectOption(productId);
  await page.getByLabel('Retrieval method').selectOption('keyword');
  await page.getByRole('button', { name: 'Inspect context', exact: true }).click();
  await settled(page);
  await expect(page.locator('.phase-context blockquote')).toContainText('40 hours');
  await page.getByRole('button', { name: 'Create versioned snapshot', exact: true }).click();
  await settled(page);
  await expect(page.getByText('Versioned evidence snapshot', { exact: true })).toBeVisible();

  const history = await (await page.request.get(`/api/sources/${sourceId}/versions`)).json();
  expect(history.versions).toHaveLength(1);
  await navigate(page, 'Content review');
  await page.getByLabel('Product to inspect').selectOption(productId);
  await page.getByRole('button', { name: 'Inspect current evidence', exact: true }).click();
  await settled(page);
  await expect(page.getByText('Product JSON-LD is blocked', { exact: false })).toBeVisible();
  await page.getByLabel('Related identifier', { exact: true }).fill(sourceId);
  await page.getByLabel('Evidence revision identifier', { exact: true }).fill(history.versions[0].revision_id);
  await page.getByLabel('Relationship').selectOption('documented_by');
  await page.getByRole('button', { name: 'Propose relationship', exact: true }).click();
  await settled(page);
  await page.getByRole('button', { name: 'Approve relationship', exact: true }).click();
  await settled(page);
  await expect(page.locator('.phase-records').filter({ hasText: 'documented_by' })).toContainText('approved');

  await navigate(page, 'Content studio');
  await page.getByLabel('Draft format').selectOption('faq');
  await page.getByRole('button', { name: row.name, exact: true }).click();
  await settled(page);
  await expect(page.locator('.core-draft-text')).toContainText('What do the sources state about battery?');
  await expect(page.locator('.core-draft-text')).toContainText('40 hours');
  await page.getByRole('button', { name: 'Approve this draft', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Approve this draft', exact: true }).click();
  await settled(page);
  await expect(page.locator('.core-draft-state')).toHaveText('approved');

  await navigate(page, 'Import catalog');
  await page.getByLabel('Catalog or source file').setInputFiles({ name: 'browser-headphone.webp', mimeType: 'image/webp', buffer: await readFile('public/images/hero-headphones.webp') });
  await page.getByLabel('Related product').selectOption(productId);
  await page.getByLabel('Stable source ID').fill(`image-${suffix}`);
  await page.getByLabel('Source revision', { exact: true }).fill('1');
  await page.getByRole('button', { name: 'Upload and process', exact: true }).click();
  await settled(page);
  await navigate(page, 'Content review');
  await page.getByLabel('Product to inspect').selectOption(productId);
  await page.getByRole('button', { name: 'Inspect current evidence', exact: true }).click();
  await settled(page);
  await page.getByRole('button', { name: 'Load image uploads', exact: true }).click();
  await settled(page);
  await page.getByLabel('Uploaded image').selectOption({ label: `browser-headphone.webp · image-${suffix}` });
  await expect(page.locator('.phase-review-image')).toBeVisible();
  await expect.poll(() => page.locator('.phase-review-image').evaluate((image) => (image as HTMLImageElement).naturalWidth)).toBeGreaterThan(0);
  await page.getByLabel('Visible image observations', { exact: true }).fill('Cream over-ear headphones against a burgundy background.');
  await page.getByLabel('Proposed alt text', { exact: true }).fill('Cream over-ear headphones with padded earcups.');
  await page.getByRole('button', { name: 'Save review', exact: true }).click();
  await settled(page);
  await page.getByRole('button', { name: 'Approve accessibility review', exact: true }).click();
  await settled(page);
  await expect(page.getByText('informative · Reviewed', { exact: true })).toBeVisible();
  const violations = (await new AxeBuilder({ page }).analyze()).violations.filter((item) => ['critical', 'serious'].includes(item.impact || ''));
  expect(violations).toEqual([]);
  await page.locator('.core-title h1').focus();
  await page.evaluate(() => scrollTo(0, 0));
  await page.screenshot({ path: `memory/screenshots/phase-real-${testInfo.project.name}.png`, fullPage: true });

  await navigate(page, 'Store connections');
  const storeResponse = await page.request.get('/api/shopify');
  expect(storeResponse.ok()).toBe(true);
  const store = await storeResponse.json();
  expect(typeof store.configured).toBe('boolean');
  expect(store.connection).toBeNull();
  await expect(page.getByRole('status').filter({ hasText: 'Not connected' })).toBeVisible();
  const connect = page.getByRole('button', { name: 'Connect read-only store', exact: true });
  const unconfigured = page.getByText('Shopify application credentials are not configured.', { exact: false });
  if (store.configured) {
    await expect(connect).toBeEnabled();
    await expect(unconfigured).toHaveCount(0);
  } else {
    await expect(connect).toBeDisabled();
    await expect(unconfigured).toBeVisible();
  }
  await expect(page.getByRole('button', { name: 'Synchronize catalog', exact: true })).toBeDisabled();
  await expect(page.getByRole('button', { name: 'Disconnect store', exact: true })).toBeDisabled();
  await navigate(page, 'Account & team');
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await settled(page);
  await expect(page.getByRole('heading', { name: 'Temporary workspace', exact: true })).toBeVisible();
  const products = await (await page.request.get('/api/products')).json();
  expect(products.products.some((product: { id: string }) => product.id === productId)).toBe(false);
  await page.getByLabel('Email address', { exact: true }).fill(email);
  await page.getByLabel('Password', { exact: true }).fill(`test-password-${suffix}`);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await settled(page);
  await expect(page.getByRole('heading', { name: email, exact: true })).toBeVisible();
  const retained = await (await page.request.get('/api/products')).json();
  expect(retained.products.some((product: { id: string }) => product.id === productId)).toBe(true);
});
